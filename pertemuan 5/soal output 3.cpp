#include <iostream>

using namespace std;

int main() {
    cout << "Contoh Program perulangan" << endl;
    // Perulangan naik dari 1 hingga 10
    for (int i = 1; i <= 10; i++) {
        cout << i << endl;
    }

    cout << "\nPerulangan menurun" << endl;
    // Perulangan menurun dari 10 hingga 1
    for (int i = 10; i >= 1; i--) {
        cout << i << endl;
    }

    return 0;
}
